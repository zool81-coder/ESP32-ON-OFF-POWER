#pragma once

// =============================================================================
//  watchdog.hpp — сторожевой таймер (Task Watchdog, TWDT)
// -----------------------------------------------------------------------------
//  Если основной цикл loop() "зависнет" дольше заданного таймаута,
//  плата автоматически перезагрузится. Это защищает устройство от
//  "зависания навсегда" (например, при неожиданной блокировке).
//
//  Используется аппаратный сторожевой таймер задач ESP32 (esp_task_wdt_*).
// =============================================================================

#include <cstdint>

namespace relay::watchdog
{

    // Инициализация: таймаут в секундах + включение наблюдения за текущей задачей.
    // Должна вызываться один раз в setup().
    void begin(uint32_t timeoutSeconds);

    // "Кормить" таймер: вызывать каждый проход loop().
    // Если не вызвать в течение таймаута — произойдёт перезагрузка.
    void feed();

    // Вывести в лог причину последней перезагрузки (полезно для диагностики).
    void logResetReason();

} // namespace relay::watchdog
