#include <cstdint>

namespace relay::power
{

    class Controller
    {
    public:
        // Состояние питания. enum class не даёт перепутать с bool/числом.
        enum class State : uint8_t
        {
            Off = 0, // питание выключено
            On = 1,  // питание включено
        };

        // Инициализирует пин и включает питание (безопасное состояние по умолчанию).
        void begin();

        // Установить питание: true = включено, false = выключено.
        void setOn(bool on);

        // Переключить питание в противоположное состояние.
        void toggle();

        // Текущее состояние.
        [[nodiscard]] bool isOn() const noexcept { return state_ == State::On; }

    private:
        State state_ = State::On; // при запуске питание всегда включено

        // Единая точка применения состояния: пин + лог.
        void apply(State state);
    };

} // namespace relay::power
