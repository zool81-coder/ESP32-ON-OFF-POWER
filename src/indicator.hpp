#pragma once

// =============================================================================
//  indicator.hpp — управление встроенным светодиодом
// -----------------------------------------------------------------------------
//  Светодиод выделен в отдельный модуль, т.к. теперь он показывает разные
//  состояния ПАТТЕРНАМИ:
//    - On  (горит)    = питание включено;
//    - Off (погашен)  = питание выключено;
//    - BlinkFast       = активен режим точки доступа (быстрое мигание).
// =============================================================================

#include <cstdint>

namespace relay::indicator
{

    class Led
    {
    public:
        // Паттерны индикации.
        enum class Pattern : uint8_t
        {
            Off = 0,       // постоянно выключен
            On = 1,        // постоянно включён
            BlinkFast = 2, // быстрое мигание (~5 Гц) — режим точки доступа
            BlinkSlow = 3, // медленное мигание (резерв)
        };

        // Настройка пина светодиода.
        void begin();

        // Задать паттерн индикации.
        void setPattern(Pattern p);

        // Вызывать в loop(): реализует мигание по таймеру.
        void update();

    private:
        Pattern pattern_ = Pattern::On; // текущий паттерн
        bool levelOn_ = true;           // текущее физическое состояние LED
        uint32_t lastToggleMs_ = 0;     // время последнего переключения

        // Применить физический уровень (учёт инверсии).
        void applyLevel(bool on);

        // Период мигания для паттерна.
        [[nodiscard]] uint32_t intervalFor(Pattern p) const;
    };

} // namespace relay::indicator
